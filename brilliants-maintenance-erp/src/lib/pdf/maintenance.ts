export interface PmSchedulePdfRow {
  schedule_no: string | null;
  equipment_code: string;
  equipment_name: string;
  task_type: string | null;
  frequency: string | null;
  last_run_at: string | null;
  next_run_at: string | null;
  assigned_to: string | null;
  is_active: boolean;
}

export interface PmPdfMeta {
  organizationName?: string | null;
  plantName?: string | null;
  /** e.g. "Overdue", "Due Today", "Upcoming (30 days)", "All" */
  filterLabel?: string;
  generatedBy?: string | null;
}

const MARGIN = 40;
const PAGE_W = 595.28;
const PAGE_H = 841.89;
const CONTENT_W = PAGE_W - MARGIN * 2;

function fmtDate(value: string | null | undefined): string {
  if (!value) return "—";
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return "—";
  return d.toLocaleDateString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
  });
}

function pretty(value: string | null | undefined): string {
  if (!value) return "—";
  return value.replace(/_/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
}

type Doc = import("jspdf").jsPDF;

function ensureSpace(doc: Doc, y: number, needed: number): number {
  if (y + needed > PAGE_H - 80) {
    doc.addPage();
    return 80;
  }
  return y;
}

function dueState(nextRunAt: string | null, isActive: boolean | null): string {
  if (!isActive) return "Inactive";
  if (!nextRunAt) return "No date";
  const now = Date.now();
  const t = new Date(nextRunAt).getTime();
  if (Number.isNaN(t)) return "—";
  if (t < now) return "OVERDUE";
  const todayStart = new Date();
  todayStart.setHours(0, 0, 0, 0);
  const todayEnd = todayStart.getTime() + 24 * 60 * 60 * 1000;
  if (t >= todayStart.getTime() && t < todayEnd) return "Due today";
  return "Upcoming";
}

/** A4 PDF report of PM schedules (due / overdue / filtered list). */
export async function downloadPmSchedulePdf(
  rows: PmSchedulePdfRow[],
  meta: PmPdfMeta = {}
): Promise<void> {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ unit: "pt", format: "a4" });

  // Header banner
  doc.setFillColor(29, 78, 216);
  doc.rect(0, 0, PAGE_W, 70, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text(meta.organizationName || "Brilliants Industrial Services", MARGIN, 34);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text(`Plant: ${meta.plantName || "All plants"}`, MARGIN, 52);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("PM Schedule Report", PAGE_W - MARGIN, 40, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.text(meta.filterLabel || "All schedules", PAGE_W - MARGIN, 58, { align: "right" });
  doc.setTextColor(17, 24, 39);

  let y = 100;

  // Meta rows
  const metaPairs: [string, string][] = [
    ["Generated On", new Date().toLocaleDateString("en-IN")],
    ["Rows", String(rows.length)],
    ["Filter", meta.filterLabel || "All"],
    ["Generated By", meta.generatedBy || "—"],
  ];
  doc.setFontSize(10);
  let x = MARGIN;
  const metaColW = CONTENT_W / metaPairs.length;
  for (const [label, value] of metaPairs) {
    doc.setTextColor(107, 114, 128);
    doc.setFont("helvetica", "normal");
    doc.text(label.toUpperCase(), x, y);
    doc.setTextColor(17, 24, 39);
    doc.setFont("helvetica", "bold");
    doc.text(value, x, y + 14);
    x += metaColW;
  }
  y += 40;

  // Table
  const cols = [
    { label: "Schedule", x: MARGIN, align: "left" as const },
    { label: "Equipment", x: MARGIN + 80, align: "left" as const },
    { label: "Task Type", x: MARGIN + 230, align: "left" as const },
    { label: "Frequency", x: MARGIN + 330, align: "left" as const },
    { label: "Next Run", x: MARGIN + 410, align: "left" as const },
    { label: "State", x: PAGE_W - MARGIN, align: "right" as const },
  ];

  const drawHeader = (yy: number): number => {
    doc.setFillColor(243, 244, 246);
    doc.rect(MARGIN, yy - 12, CONTENT_W, 22, "F");
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(55, 65, 81);
    for (const c of cols) doc.text(c.label, c.x, yy + 3, { align: c.align });
    return yy + 24;
  };

  y = drawHeader(y);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);

  rows.forEach((row) => {
    y = ensureSpace(doc, y, 20);
    const state = dueState(row.next_run_at, row.is_active);
    doc.setTextColor(17, 24, 39);
    doc.text((row.schedule_no ?? "—").slice(0, 14), cols[0].x, y);
    doc.text(
      `${row.equipment_code || "—"} ${row.equipment_name || ""}`.trim().slice(0, 30),
      cols[1].x,
      y
    );
    doc.text((pretty(row.task_type) ?? "—").slice(0, 18), cols[2].x, y);
    doc.text(pretty(row.frequency).slice(0, 14), cols[3].x, y);
    doc.text(fmtDate(row.next_run_at), cols[4].x, y);
    if (state === "OVERDUE") doc.setTextColor(220, 38, 38);
    else if (state === "Due today") doc.setTextColor(217, 119, 6);
    else doc.setTextColor(55, 65, 81);
    doc.text(state, cols[5].x, y, { align: "right" });
    doc.setTextColor(17, 24, 39);
    y += 18;
  });

  // Footer signature
  y = ensureSpace(doc, y, 70);
  y += 30;
  doc.setDrawColor(209, 213, 219);
  const labels = ["Prepared By", "Reviewed By (Manager)"];
  const colW = CONTENT_W / labels.length;
  labels.forEach((label, i) => {
    const lx = MARGIN + colW * i;
    doc.line(lx, y, lx + colW - 30, y);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(107, 114, 128);
    doc.text(label, lx, y + 12);
  });

  const filterSlug = (meta.filterLabel || "all")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
  doc.save(`pm-${filterSlug}.pdf`);
}
